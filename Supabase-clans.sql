create or replace function public.element6_get_or_create_leader_thread(p_other_clan uuid)
returns public.element6_clan_leader_threads
language plpgsql security definer set search_path=public
as $$
declare
  v_user uuid:=auth.uid();
  v_my_clan uuid;
  v_row public.element6_clan_leader_threads;
  a uuid;
  b uuid;
begin
  select clan_id into v_my_clan from public.element6_clan_members
  where user_id=v_user and role='leader';
  if v_my_clan is null then raise exception 'Only clan leaders can use leader chat'; end if;
  if not exists(select 1 from public.element6_clans where id=p_other_clan) then raise exception 'Clan not found'; end if;
  if v_my_clan=p_other_clan then raise exception 'Choose another clan'; end if;

  a:=least(v_my_clan,p_other_clan);
  b:=greatest(v_my_clan,p_other_clan);

  select * into v_row from public.element6_clan_leader_threads
  where clan_a_id=a and clan_b_id=b
  limit 1;

  if v_row.id is null then
    insert into public.element6_clan_leader_threads(clan_a_id,clan_b_id)
    values(a,b)
    on conflict do nothing;
    select * into v_row from public.element6_clan_leader_threads
    where clan_a_id=a and clan_b_id=b
    limit 1;
  end if;
  return v_row;
end;
$$;
revoke all on function public.element6_get_or_create_leader_thread(uuid) from public,anon;
grant execute on function public.element6_get_or_create_leader_thread(uuid) to authenticated;

create or replace function public.element6_claim_clan_reward(p_tier smallint)
returns integer
language plpgsql security definer set search_path=public
as $$
declare
  v_user uuid:=auth.uid();
  v_clan uuid;
  v_reward integer;
begin
  select clan_id into v_clan from public.element6_clan_members where user_id=v_user;
  if v_clan is null then raise exception 'Not in a clan'; end if;
  if not exists(select 1 from public.element6_clans where id=v_clan and tier>=p_tier) then raise exception 'Tier not reached'; end if;
  select token_reward into v_reward from public.element6_clan_rewards where tier=p_tier;
  if v_reward is null then raise exception 'Reward not found'; end if;

  insert into public.element6_clan_reward_claims(clan_id,user_id,tier)
  values(v_clan,v_user,p_tier)
  on conflict do nothing;

  if not found then raise exception 'Reward already claimed'; end if;
  return v_reward;
end;
$$;
revoke all on function public.element6_claim_clan_reward(smallint) from public,anon;
grant execute on function public.element6_claim_clan_reward(smallint) to authenticated;

create or replace function public.element6_set_clan_meeting_status(p_meeting_id uuid,p_status text)
returns void
language plpgsql security definer set search_path=public
as $$
declare
  v_user uuid:=auth.uid();
  v_clan uuid;
begin
  if p_status not in ('accepted','declined','cancelled','completed') then raise exception 'Invalid meeting status'; end if;
  select clan_id into v_clan from public.element6_clan_members where user_id=v_user and role='leader';
  if v_clan is null then raise exception 'Only leaders can manage meetings'; end if;
  update public.element6_clan_meetings
  set status=p_status,updated_at=now()
  where id=p_meeting_id
    and (organizer_clan_id=v_clan or invited_clan_id=v_clan);
end;
$$;
