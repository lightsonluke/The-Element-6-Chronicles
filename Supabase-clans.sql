create table if not exists public.element6_clans (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  name_key text generated always as (lower(regexp_replace(trim(name), '\s+', ' ', 'g'))) stored,
  tag text not null,
  tag_key text generated always as (upper(trim(tag))) stored,
  bio text not null default '',
  icon_url text,
  owner_id uuid not null references auth.users(id) on delete restrict,
  tier smallint not null default 0 check (tier between 0 and 10),
  xp bigint not null default 0 check (xp >= 0),
  tier1_unlocked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

