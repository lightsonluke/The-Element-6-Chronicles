create or replace function public.element6_review_clan_application(p_application_id uuid,p_approve boolean)
returns public.element6_clan_applications
language plpgsql security definer set search_path=public
as $$
declare
  a public.element6_clan_applications;
  v_user uuid:=auth.uid();
  v_role text;
begin
  select * into a from public.element6_clan_applications where id=p_application_id for update;
  if a.id is null then raise exception 'Application not found'; end if;
  select role into v_role from public.element6_clan_members where clan_id=a.clan_id and user_id=v_user;
  if v_role <> 'leader' then raise exception 'Only the clan leader can approve applications'; end if;
  if a.status <> 'pending' then raise exception 'Application already reviewed'; end if;

  if p_approve then
    if exists(select 1 from public.element6_clan_members where user_id=a.user_id) then raise exception 'Player is already in a clan'; end if;
    insert into public.element6_clan_members(clan_id,user_id,role) values(a.clan_id,a.user_id,'member');
    update public.element6_clan_applications set status='approved',reviewed_at=now(),reviewed_by=v_user where id=a.id;
  else
    update public.element6_clan_applications set status='rejected',reviewed_at=now(),reviewed_by=v_user where id=a.id;
  end if;
  select * into a from public.element6_clan_applications where id=a.id;
  return a;
end;
$$;
revoke all on function public.element6_review_clan_application(uuid,boolean) from public,anon;
grant execute on function public.element6_review_clan_application(uuid,boolean) to authenticated;

