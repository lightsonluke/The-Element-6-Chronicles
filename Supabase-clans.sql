-- Tier 0 -> Tier 1 happens on the first qualifying match/event.
-- Later tiers require both activity XP and minimum elapsed clan age.
create or replace function public.element6_clan_required_xp(p_tier smallint)
returns bigint language sql immutable as $$
  select case p_tier
    when 0 then 1
    when 1 then 75
    when 2 then 250
    when 3 then 550
    when 4 then 1000
    when 5 then 1600
    when 6 then 2400
    when 7 then 3400
    when 8 then 4700
    when 9 then 6500
    else 0
  end;
$$;

create or replace function public.element6_clan_min_days_for_tier(p_tier smallint)
returns integer language sql immutable as $$
  select case p_tier
    when 1 then 0
    when 2 then 7
    when 3 then 21
    when 4 then 45
    when 5 then 75
    when 6 then 110
    when 7 then 150
    when 8 then 200
    when 9 then 270
    when 10 then 365
    else 0
  end;
$$;

-- IMPORTANT: this is the secure server-side hook the game should call
-- after a qualifying match is genuinely completed. The browser cannot
-- directly promote a clan or award XP through the table policies.
create or replace function public.element6_record_clan_activity(
  p_user_id uuid,
  p_event_key text,
  p_xp integer,
  p_source_match_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_clan public.element6_clans%rowtype;
  v_member boolean;
  v_new_tier smallint;
begin
  if p_user_id is null then raise exception 'Missing user'; end if;
  if p_xp < 0 then raise exception 'Invalid XP'; end if;

  select exists(
    select 1 from public.element6_clan_members
    where clan_id is not null and user_id=p_user_id
  ) into v_member;

  if not v_member then
    return jsonb_build_object('recorded',false,'reason','not_in_clan');
  end if;

  select c.* into v_clan
  from public.element6_clans c
  join public.element6_clan_members m on m.clan_id=c.id
  where m.user_id=p_user_id
  for update;

  if v_clan.id is null then
    return jsonb_build_object('recorded',false,'reason','not_in_clan');
  end if;

  if p_source_match_id is not null then
    insert into public.element6_clan_activity_events(clan_id,user_id,event_key,xp,source_match_id)
    values(v_clan.id,p_user_id,p_event_key,greatest(0,p_xp),p_source_match_id)
    on conflict do nothing;
  else
    insert into public.element6_clan_activity_events(clan_id,user_id,event_key,xp)
    values(v_clan.id,p_user_id,p_event_key,greatest(0,p_xp));
  end if;

  if p_source_match_id is not null and not found then
    return jsonb_build_object('recorded',false,'reason','already_recorded','tier',v_clan.tier,'xp',v_clan.xp);
  end if;

  update public.element6_clans
  set xp=xp+greatest(0,p_xp),
      tier=greatest(tier,
        case
          when tier=0 then 1
          else tier
        end
      ),
      tier1_unlocked_at=coalesce(tier1_unlocked_at,now()),
      updated_at=now()
  where id=v_clan.id;

  select * into v_clan from public.element6_clans where id=v_clan.id for update;

  v_new_tier:=v_clan.tier;
  while v_new_tier < 10
    and v_clan.xp >= public.element6_clan_required_xp(v_new_tier)
    and now() >= v_clan.created_at + make_interval(days => public.element6_clan_min_days_for_tier(v_new_tier+1))
  loop
    v_new_tier:=v_new_tier+1;
  end loop;

  if v_new_tier <> v_clan.tier then
    update public.element6_clans
    set tier=v_new_tier, updated_at=now()
    where id=v_clan.id;
  end if;

  return jsonb_build_object('recorded',true,'clan_id',v_clan.id,'tier',v_new_tier,'xp',v_clan.xp);
end;
$$;

revoke all on function public.element6_record_clan_activity(uuid,text,integer,text) from public,anon;
grant execute on function public.element6_record_clan_activity(uuid,text,integer,text) to authenticated;

-- One secure read model for the clan member ELO screen.
create or replace function public.element6_get_clan_member_elo(p_clan_id uuid)
returns table(
  user_id uuid,
  username text,
  role text,
  ranked_rating integer,
  ranked_wins integer,
  ranked_losses integer,
  ranked_matches integer,
  soccer_rating integer,
  soccer_wins integer,
  soccer_losses integer,
  soccer_matches integer,
  volleyball_rating integer,
  volleyball_wins integer,
  volleyball_losses integer,
  volleyball_matches integer,
  dodgeball_rating integer,
  dodgeball_wins integer,
  dodgeball_losses integer,
  dodgeball_matches integer
)
language sql
security definer
set search_path=public
as $$
  select
    m.user_id,
    coalesce(pp.username,'Player'),
    m.role,
    coalesce(rr.rating,1000),
    coalesce(rr.wins,0),
    coalesce(rr.losses,0),
    coalesce(rr.matches_played,0),
    coalesce(soc.rating,1000),
    coalesce(soc.wins,0),
    coalesce(soc.losses,0),
    coalesce(soc.matches_played,0),
    coalesce(vb.rating,1000),
    coalesce(vb.wins,0),
    coalesce(vb.losses,0),
    coalesce(vb.matches_played,0),
    coalesce(db.rating,1000),
    coalesce(db.wins,0),
    coalesce(db.losses,0),
    coalesce(db.matches_played,0)
  from public.element6_clan_members m
  left join public.player_profiles pp on pp.user_id=m.user_id
  left join public.ranked_ratings rr on rr.user_id=m.user_id
  left join public.online_sport_ratings soc on soc.user_id=m.user_id and soc.mode='soccer_ranked'
  left join public.online_sport_ratings vb on vb.user_id=m.user_id and vb.mode='volleyball_1v1_ranked'
  left join public.online_sport_ratings db on db.user_id=m.user_id and db.mode='dodgeball_ranked'
  where m.clan_id=p_clan_id
    and exists(
      select 1 from public.element6_clan_members me
      where me.clan_id=p_clan_id and me.user_id=auth.uid()
    )
  order by m.role='leader' desc, m.joined_at, pp.username;
$$;

revoke all on function public.element6_get_clan_member_elo(uuid) from public,anon;
grant execute on function public.element6_get_clan_member_elo(uuid) to authenticated;

-- Secure RPCs for membership management.
create or replace function public.element6_create_clan(
  p_name text,p_tag text,p_bio text default '',p_icon_url text default null
)
returns public.element6_clans
language plpgsql security definer set search_path=public
as $$
declare
  v_user uuid:=auth.uid();
  v_clan public.element6_clans;
begin
  if v_user is null then raise exception 'Sign in first'; end if;
  if exists(select 1 from public.element6_clan_members where user_id=v_user) then raise exception 'You are already in a clan'; end if;
  if char_length(trim(p_name)) not between 3 and 24 then raise exception 'Clan name must be 3-24 characters'; end if;
  if p_tag is null or trim(p_tag) !~ '^[A-Za-z0-9]{2,6}$' then raise exception 'Clan tag must be 2-6 letters or numbers'; end if;

  -- Token deduction is intentionally delegated to the existing account economy
  -- through the client integration callback. This RPC only creates the clan.
  insert into public.element6_clans(name,tag,bio,icon_url,owner_id)
  values(trim(p_name),upper(trim(p_tag)),left(coalesce(p_bio,''),500),p_icon_url,v_user)
  returning * into v_clan;

  insert into public.element6_clan_members(clan_id,user_id,role)
  values(v_clan.id,v_user,'leader');

  return v_clan;
end;
$$;
revoke all on function public.element6_create_clan(text,text,text,text) from public,anon;
grant execute on function public.element6_create_clan(text,text,text,text) to authenticated;

