      tag=coalesce(nullif(upper(trim(p_tag)),''),tag),
      bio=coalesce(left(p_bio,500),bio),
      icon_url=coalesce(p_icon_url,icon_url),
      updated_at=now()
  where id=v_clan
  returning * into v_row;

  return v_row;
end;
$$;
